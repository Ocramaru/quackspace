"""Generate the AI-navigation layer from the space's files + links.

Derived artifacts, all regenerated each run (idempotent, incremental):

  <folder>/.index.yaml   editable: this folder's direct `files:` AND direct
                         `directories:` (immediate subfolders). Written for
                         every folder, including subdir-only folders and root.
  .quack/map.yaml        global: the full nested folder tree, each folder with
                         description, diagram, counts, and type/tag rollups,
                         plus a space-level rollup.
  .quack/quack.duckdb    the catalog: files, folders, tags, links + FTS.

Folder metadata (per-folder `directories:` sections, `map.yaml`, and the
catalog `folders` table) all come from one shared resolver (`folders.py`), so
they cannot drift. Recognition defaults give well-known files/folders an
instant description, written non-sticky (blank `described_at`) so they
re-derive and never masquerade as authored.

The drill-down an AI follows: map.yaml (which folder?) -> folder/.index.yaml
(which child file or subfolder?) -> the file -> `quack search`/`quack sql` to
pull just the related slice from the catalog. Read cost scales with relevance,
not space size.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from . import catalog, folders, index_store
from .config import Config
from .folders import FolderInfo
from .core import Space, find_root, scan_signature

GENERATED_HEADER = (
    "# GENERATED by `quack reindex`, do not edit by hand.\n"
)


def write_folder_indexes(
    space: Space,
    folder_infos: dict[str, FolderInfo],
    dirty_folders: set[Path] | None = None,
) -> list[Path]:
    """Write/merge one editable .index.yaml per folder — including folders that
    contain only subfolders, and the root — each listing its direct ``files:``
    and direct ``directories:``.

    When *dirty_folders* is supplied only those folders are (re)written; pass
    ``None`` to write every folder (full rebuild). Truly-empty folders (no
    direct files and no subfolders) are skipped.
    """
    grouped: dict[str, list] = defaultdict(list)
    for e in space.entries:
        grouped[e.folder].append(e)
    kids_by_parent = folders.children_index(folder_infos)

    dirty_resolved = (
        {p.resolve() for p in dirty_folders} if dirty_folders is not None else None
    )

    written: list[Path] = []
    for rel, info in folder_infos.items():
        folder = space.root if info.is_root else space.root / rel
        if dirty_resolved is not None and folder.resolve() not in dirty_resolved:
            continue
        file_rows = [
            {
                "name": e.path.name,
                "description": e.description,
                "tags": e.tags,
                "links": e.links,
                "file_modified": e.modified,
                "described_at": e.described_at,
            }
            for e in sorted(grouped.get(rel, []), key=lambda x: x.name.lower())
        ]
        dir_rows = [
            {
                "name": c.name,
                "description": c.description,
                "tags": c.tags,
                "n_files": c.n_files,
                "diagram": c.diagram,
                "types": c.types,
                "described_at": c.described_at,
            }
            for c in kids_by_parent.get(rel, [])
        ]
        if not file_rows and not dir_rows:
            # Folder has nothing to describe. Remove any index left over from
            # when it did, so it can't list now-deleted children forever.
            stale = index_store.index_path(folder)
            if stale.exists():
                stale.unlink()
            continue
        written.append(index_store.write_index(folder, file_rows, dir_rows))
    return written


def write_map(space: Space, folder_infos: dict[str, FolderInfo]) -> Path:
    """Write the global folder-level map: the full nested tree, each folder
    enriched with description, diagram, counts, and type/tag rollups, plus a
    space-level rollup. Derived from the shared folder resolver."""
    tree: dict[str, dict] = {}
    for rel in sorted(r for r in folder_infos if r != ""):
        info = folder_infos[rel]
        entry: dict = {
            "description": info.description or "(no description)",
            "files": info.n_files,
        }
        if info.diagram:
            entry["diagram"] = info.diagram
        if info.types:
            entry["types"] = info.types
        if info.tag_rollup:
            entry["tags"] = info.tag_rollup
        tree[rel] = entry

    space_types: Counter = Counter()
    space_tags: Counter = Counter()
    for e in space.entries:
        space_types[e.ext or "other"] += 1
        space_tags.update(e.tags)

    out = space.root / ".quack" / "map.yaml"
    out.write_text(
        GENERATED_HEADER
        + index_store.fast_dump(
            {
                "space": space.root.name,
                "files": len(space.entries),
                "types": dict(space_types),
                "tags": [t for t, _ in space_tags.most_common(10)],
                "folders": tree,
            }
        )
    )
    return out


def _expand_dirty(dirty: set[Path], root: Path) -> set[Path]:
    """Add every ancestor folder (up to and including root) of each dirty
    folder, since a child's counts/rollups change its parents' ``directories:``
    sections."""
    root = root.resolve()
    out: set[Path] = set()
    for p in dirty:
        cur = p.resolve()
        while True:
            out.add(cur)
            if cur == root or root not in cur.parents:
                break
            cur = cur.parent
    out.add(root)
    return out


def _folder_path(root: Path, rel: str) -> Path:
    """Filesystem path of a folder rel ("" → root)."""
    return root if rel == "" else root / rel


def _parent_folder_path(root: Path, rel: str) -> Path:
    """Filesystem path of the folder whose index *describes* folder *rel* —
    i.e. its parent ("" → root)."""
    parent_rel = rel.rsplit("/", 1)[0] if "/" in rel else ""
    return _folder_path(root, parent_rel)


@dataclass
class _Dirty:
    """What a reindex needs to do, derived by diffing the loaded space against
    the stored catalog."""

    full_rebuild: bool  # no/invalid catalog → build everything from scratch
    folders: set[Path]  # folders whose .index.yaml must be (re)written
    need_full: bool  # a text/content change requires a full catalog + FTS build

    @property
    def nothing_to_do(self) -> bool:
        return not self.full_rebuild and not self.folders


def _compute_dirty(
    space: Space, folder_infos: dict[str, FolderInfo]
) -> _Dirty:
    """Diff the loaded space against the stored catalog.

    Compares each file's current mtime, description, tags, and described_at —
    and each folder's resolved description/counts/diagram — directly against
    what is stored. No timestamp arithmetic, no sub-second races. Deleted
    files/folders are detected by set-diffing indexed vs current.

    ``need_full`` is set when a change touches the full-text surface (a file
    added/removed, or its name/body/description changed): DuckDB's FTS index is
    rebuilt wholesale, so those require a full catalog build. Changes that don't
    touch text (tags, described_at, folder metadata) take the light in-place
    path — bodies, links, inbound counts, and the FTS index are provably
    unchanged, since links/inbound derive from bodies.
    """
    db = catalog.db_path(space)
    if not db.exists():
        return _Dirty(full_rebuild=True, folders=set(), need_full=True)

    try:
        con = catalog.connect_path(db)
        try:
            rows = con.execute(
                "SELECT rel, file_modified, description, tags_csv, described_at FROM files"
            ).fetchall()
            folder_rows = con.execute(
                "SELECT folder, description, n_files, diagram, described_at FROM folders"
            ).fetchall()
        finally:
            con.close()
    except Exception:
        # Any error (corrupt DB, schema mismatch, I/O) → full rebuild is safe.
        return _Dirty(full_rebuild=True, folders=set(), need_full=True)

    # Build a lookup keyed by rel for O(1) comparisons.
    indexed: dict[str, tuple[str, str, str, str]] = {
        rel: (file_mod or "", desc or "", tags_csv or "", desc_at or "")
        for rel, file_mod, desc, tags_csv, desc_at in rows
    }
    indexed_rels = set(indexed)
    current_rels = {e.rel for e in space.entries}
    root = space.root
    dirty: set[Path] = set()
    need_full = False

    for e in space.entries:
        if e.rel not in indexed:
            dirty.add(e.path.parent)  # new file → must enter the FTS index
            need_full = True
            continue
        stored_mtime, stored_desc, stored_tags_csv, stored_desc_at = indexed[e.rel]
        changed = False
        if e.modified != stored_mtime or e.description != stored_desc:
            changed = True
            need_full = True  # body/description may have changed → FTS rebuild
        if ",".join(e.tags) != stored_tags_csv or e.described_at != stored_desc_at:
            changed = True  # non-text metadata → light path is enough
        if changed:
            dirty.add(e.path.parent)

    # Deleted files — mark the folder they used to live in; corpus changed.
    for rel in indexed_rels - current_rels:
        need_full = True
        folder_part = rel.rsplit("/", 1)[0] if "/" in rel else "."
        dirty.add((root / folder_part).resolve() if folder_part != "." else root.resolve())

    # Folder metadata drift (authored/vanished description, changed counts, a
    # newly generated diagram). The folder is described in its *parent's*
    # index, so mark the parent dirty. None of this touches the FTS surface.
    stored_folders = {
        f: (d or "", int(n or 0), dg or "", da or "")
        for f, d, n, dg, da in folder_rows
    }
    current_folders = {
        i.rel: (i.description, i.n_files, i.diagram, i.described_at)
        for i in folder_infos.values()
        if not i.is_root
    }
    for rel, cur in current_folders.items():
        if stored_folders.get(rel) != cur:
            dirty.add(_parent_folder_path(root, rel))
    for rel in set(stored_folders) - set(current_folders):  # vanished folder
        dirty.add(_parent_folder_path(root, rel))

    return _Dirty(full_rebuild=False, folders=dirty, need_full=need_full)


def _dirty_folders(
    space: Space, folder_infos: dict[str, FolderInfo]
) -> set[Path] | None:
    """Folders whose index must be rewritten, or None for a full build.
    Thin wrapper over :func:`_compute_dirty` for callers/tests that only need
    the folder set."""
    d = _compute_dirty(space, folder_infos)
    return None if d.full_rebuild else d.folders


def _fast_noop(
    root: Path,
    *,
    store_body: bool,
    progress: Callable[[int, int, str], None] | None = None,
) -> dict | None:
    """Return the no-op reindex summary if a stat-only check proves nothing
    changed since the last build, else None. Conservative: any uncertainty
    (a touched metadata file, a folder/file set difference, a changed mtime)
    returns None so the accurate full path runs. Never reports a false no-op."""
    db = root / ".quack" / catalog.DB_NAME
    if not db.exists():
        return None
    if not catalog.store_body_matches(db, store_body):
        return None
    try:
        con = catalog.connect_path(db)
        try:
            stored_files = {
                rel: (fm or "")
                for rel, fm in con.execute(
                    "SELECT rel, file_modified FROM files"
                ).fetchall()
            }
            stored_folders = {
                f for (f,) in con.execute("SELECT folder FROM folders").fetchall()
            }
            row = con.execute(
                "SELECT value FROM metadata WHERE key = 'built_at_ns'"
            ).fetchone()
        finally:
            con.close()
    except Exception:
        return None
    if row is None:
        return None
    try:
        built_at_ns = int(row[0])
    except (TypeError, ValueError):
        return None

    files, folders_now, newest_marker_ns = scan_signature(root, progress=progress)
    if newest_marker_ns > built_at_ns:  # a .index.yaml/.folder.md edited since build
        return None
    if set(files) != set(stored_files) or folders_now != stored_folders:
        return None
    for rel, mtime in files.items():
        if mtime != stored_files[rel]:
            return None

    return {
        "space": str(root),
        "files": len(stored_files),
        "folder_indexes": 0,
        "catalog": "skipped",
        "map": str(root / ".quack" / "map.yaml"),
        "db": str(db),
    }


def reindex(
    explicit_root: str | None = None,
    progress: Callable[[int, int, str], None] | None = None,
) -> dict:
    """Regenerate all derived artifacts. Returns a summary.

    *progress*, if given, is called as ``progress(done, total, message)`` at each
    phase so a caller (the CLI) can drive a status animation.

    Incremental in three tiers, decided by diffing the loaded space against the
    stored catalog (see :func:`_compute_dirty`):

    * **skipped** — nothing changed: returns immediately, touches nothing.
    * **light** — only non-text metadata changed (tags, described_at, folder
      descriptions/counts/diagram): rewrites just the affected `.index.yaml`
      files and updates the catalog's file-metadata/tags/folders rows in place,
      leaving bodies, links, inbound counts, and the FTS index untouched.
    * **full** — a file was added/removed or its name/body/description changed:
      the FTS index must be rebuilt wholesale, so the whole catalog is rebuilt.

    A stat-only no-op pre-check runs first: if nothing changed it returns
    without the full Space.load (which reads every file). Only when it can't be
    sure do we pay for the full load + the tiered diff above.

    The graph lives in the DuckDB catalog (links table + recursive-CTE
    traversal), not a separate graph.json: `quack search`/`quack sql` pull
    only the slice they need into context instead of loading the whole graph.
    """
    from .gitignore import ensure_gitignore

    # Fast path: a stat-only signature check that avoids reading any file when
    # nothing has changed (the common reindex). Conservative — any doubt falls
    # through to the accurate full path below.
    root = find_root(explicit_root)
    config = Config.load(str(root))
    store_body = config.index.store_body
    catalog_path = root / ".quack" / catalog.DB_NAME
    catalog_mode_changed = not catalog.store_body_matches(catalog_path, store_body)
    noop = _fast_noop(root, store_body=store_body, progress=progress)
    if noop is not None:
        ensure_gitignore(root)
        return noop

    # Space.load drives the per-file scan progress. Later phases usually don't
    # have fine-grained counts, so they get their own small start/done bars.
    space = Space.load(explicit_root, progress=progress)

    def _phase_start(message: str) -> None:
        if progress is not None:
            progress(0, 1, message)

    def _phase_done(message: str) -> None:
        if progress is not None:
            progress(1, 1, message)

    ensure_gitignore(space.root)

    # Resolve folder metadata once and feed it to every consumer (dirty
    # detection, indexes, map, catalog) so they can't drift.
    _phase_start("Resolving folder metadata")
    folder_infos = folders.resolve_folders(space)
    _phase_done("Resolved folder metadata")
    _phase_start("Checking catalog changes")
    d = _compute_dirty(space, folder_infos)
    _phase_done("Checked catalog changes")

    if d.nothing_to_do and not catalog_mode_changed:
        # Nothing changed — return without touching any files.
        _phase_done("Already up to date")
        return {
            "space": str(space.root),
            "files": len(space.entries),
            "folder_indexes": 0,
            "catalog": "skipped",
            "map": str(space.root / ".quack" / "map.yaml"),
            "db": str(catalog.db_path(space)),
        }

    # When only some folders are dirty, also refresh their ancestors, whose
    # directory rollups changed.
    _phase_start("Writing folder indexes")
    dirty = None if d.full_rebuild else _expand_dirty(d.folders, space.root)
    indexes = write_folder_indexes(space, folder_infos, dirty_folders=dirty)
    _phase_done("Wrote folder indexes")
    _phase_start("Writing map")
    map_path = write_map(space, folder_infos)
    _phase_done("Wrote map")

    _phase_start("Building catalog")
    if d.full_rebuild or d.need_full or catalog_mode_changed:
        cat = catalog.build(space, folder_infos, store_body=store_body)
        mode = "full"
    else:
        cat = catalog.update_light(space, folder_infos)
        mode = "light"
    _phase_done("Built catalog")

    return {
        "space": str(space.root),
        "files": len(space.entries),
        "folder_indexes": len(indexes),
        "catalog": mode,
        "map": str(map_path),
        "db": cat["db"],
    }
